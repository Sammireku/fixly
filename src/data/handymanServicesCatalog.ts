export function getSubserviceById(subserviceId: string): HandymanSubservice | undefined {
  for (const cat of HANDYMAN_CATALOG) {
    const found = cat.services.find((s) => s.id === subserviceId);
    if (found) return found;
  }
  return undefined;
}

export function searchSubservices(query: string): HandymanSubservice[] {
  const q = query.toLowerCase().trim();
  if (!q) return [];
  const results: HandymanSubservice[] = [];
  for (const cat of HANDYMAN_CATALOG) {
    for (const s of cat.services) {
      if (
        s.serviceName.toLowerCase().includes(q) ||
        s.jobDescription.toLowerCase().includes(q) ||
        s.categoryName.toLowerCase().includes(q)
      ) {
        results.push(s);
      }
    }
  }
  return results;
}
